@dataclass(frozen=True)
class Task:
    study: str
    distribution: str
    setting: float
    repetition: int

    @property
    def key(self) -> tuple[str, str, float, int]:
        return self.study, self.distribution, self.setting, self.repetition


def _tasks(studies: tuple[str, ...]) -> list[Task]:
    tasks: list[Task] = []
    if "benchmark" in studies:
        tasks.extend(
            Task("benchmark", distribution, lhs, repetition)
            for distribution in DISTRIBUTIONS
            for lhs in BENCHMARK_LHS
            for repetition in range(REPETITIONS)
        )
    if "scarce" in studies:
        tasks.extend(
            Task("scarce", distribution, threshold, repetition)
            for distribution in DISTRIBUTIONS
            for threshold in SCARCE_THRESHOLDS
            for repetition in range(REPETITIONS)
        )
    return tasks


def _valid_interval(result: object) -> tuple[float, float]:
    try:
        values = list(result)  # type: ignore[arg-type]
        if len(values) != 2:
            return 0.0, 0.0
        lower, upper = float(values[0]), float(values[1])
        if not math.isfinite(lower) or not math.isfinite(upper):
            return math.nan, math.nan
        return lower, upper
    except (TypeError, ValueError):
        return 0.0, 0.0


def _run_task(task: Task) -> list[dict[str, object]]:
    # calibration._bootstrap_sample_factory reads this setting at call time.
    # Worker tasks are sequential within each spawned process, so selecting
    # the manuscript vintage here is local to the complete replicate group.
    os.environ["ROBUSTTAIL_BOOTSTRAP_RNG"] = BOOTSTRAP_RNG_BY_STUDY[task.study]
    module = DATA_MODULES[task.distribution]
    params = data_utils.DISTRIBUTION_DEFAULT_PARAMETERS[task.distribution]
    sample_size = 500 if task.study == "benchmark" else 30
    lhs_quantile = task.setting if task.study == "benchmark" else 0.90
    threshold = 0.70 if task.study == "benchmark" else task.setting
    sample = data_utils.generate_synthetic_data(
        module,
        params,
        sample_size,
        RANDOM_SEED + task.repetition,
    )
    lhs = float(data_utils.get_quantile(module, lhs_quantile, params))
    rhs = float(data_utils.get_quantile(module, lhs_quantile + TRUE_VALUE, params))
    dro_interval = _valid_interval(
        estimate_tail_probability_D2_chi2_only(
            input_data=sample,
            left_end_point_objective=lhs,
            right_end_point_objective=rhs,
            threshold_percentage=threshold,
            g_ellipsoidal_dimension=ELLIPSOIDAL_DIMENSION,
            alpha=ALPHA,
            random_state=RANDOM_SEED + task.repetition,
            bootstrapping_size=BOOTSTRAPPING_SIZE,
            right_endpoint=np.inf,
        )
    )
    intervals: dict[str, tuple[float, float]] = {"dro": dro_interval}
    methods = STUDY_METHODS[task.study]
    for method in methods[1:]:
        intervals[method] = _valid_interval(
            benchmark_estimate_tail_probability(
                input_data=sample,
                left_end_point_objective=lhs,
                right_end_point_objective=rhs,
                alpha=ALPHA,
                method=method,
                threshold_percentage=threshold if task.study == "scarce" else None,
                random_state=RANDOM_SEED + task.repetition,
            )
        )
    return [
        {
            "study": task.study,
            "distribution": task.distribution,
            "setting": task.setting,
            "repetition": task.repetition,
            "method": method,
            "lower_bound": intervals[method][0],
            "upper_bound": intervals[method][1],
        }
        for method in methods
    ]


def _read(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        return []
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def _write_atomic(
    path: Path,
    rows: list[dict[str, object]],
    order: dict[tuple[str, str, float, int, str], int],
) -> None:
    temporary = path.with_suffix(path.suffix + ".tmp")
    ordered = sorted(
        rows,
        key=lambda row: order[
            (
                str(row["study"]),
                str(row["distribution"]),
                float(row["setting"]),
                int(row["repetition"]),
                str(row["method"]),
            )
        ],
    )
    with temporary.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(ordered)
    temporary.replace(path)


def generate(output_dir: Path, studies: tuple[str, ...], workers: int) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)
    tasks = _tasks(studies)
    row_keys = [
        (task.study, task.distribution, task.setting, task.repetition, method)
        for task in tasks
        for method in STUDY_METHODS[task.study]
    ]
    order = {key: index for index, key in enumerate(row_keys)}
    final_path = output_dir / "raw_results.csv"
    partial_path = output_dir / "raw_results.partial.csv"
    existing = _read(final_path) or _read(partial_path)
    rows: list[dict[str, object]] = [dict(row) for row in existing]
    completed_methods: dict[tuple[str, str, float, int], set[str]] = {}
    for row in existing:
        key = (
            row["study"],
            row["distribution"],
            float(row["setting"]),
            int(row["repetition"]),
        )
        completed_methods.setdefault(key, set()).add(row["method"])
    malformed = [
        key
        for key, methods in completed_methods.items()
        if methods != set(STUDY_METHODS[key[0]])
    ]
    if malformed:
        raise ValueError(f"Checkpoint has incomplete replicate groups: {malformed[:3]}")
    completed = set(completed_methods)
    expected = {task.key for task in tasks}
    if not completed.issubset(expected):
        raise ValueError("Output directory contains rows outside the requested studies")
    pending = [task for task in tasks if task.key not in completed]
    LOGGER.info(
        "%d/%d replicate groups complete (%d method rows); %d pending",
        len(completed),
        len(tasks),
        len(existing),
        len(pending),
    )
    started = time.monotonic()
    context = multiprocessing.get_context("spawn")
    with context.Pool(
        processes=workers,
        maxtasksperchild=MAX_TASKS_PER_WORKER,
    ) as pool:
        for completed_now, result_rows in enumerate(
            pool.imap_unordered(_run_task, pending, chunksize=1), start=1
        ):
            rows.extend(result_rows)
            done = len(completed) + completed_now
            if completed_now == 1 or done % max(1, len(tasks) // 100) == 0 or done == len(tasks):
                _write_atomic(partial_path, rows, order)
                elapsed = time.monotonic() - started
                rate = completed_now / max(elapsed, 1e-9)
                LOGGER.info(
                    "Progress %d/%d replicate groups (%.1f%%); elapsed %.1fs; ETA %.1fs",
                    done,
                    len(tasks),
                    100 * done / len(tasks),
                    elapsed,
                    (len(tasks) - done) / rate,
                )
    _write_atomic(final_path, rows, order)
    partial_path.unlink(missing_ok=True)
    return final_path


def _half_width(values: np.ndarray, denominator: int | None = None) -> float:
    """Return the manuscript's normal half-width.

    Table 4.2 divides by the 200 experiment repetitions.  The retained
    Table 4.3 aggregation instead divides by the scarce sample size 30; that
    convention is evident from every displayed half-width and is preserved
    here for exact manuscript comparison.
    """
    return float(
        1.96
        * np.std(values, ddof=1)
        / math.sqrt(values.size if denominator is None else denominator)
    )


def aggregate(raw_path: Path, study: str) -> list[dict[str, object]]:
    rows = [row for row in _read(raw_path) if row["study"] == study]
    settings = BENCHMARK_LHS if study == "benchmark" else SCARCE_THRESHOLDS
    methods = STUDY_METHODS[study]
    expected_count = len(DISTRIBUTIONS) * len(settings) * REPETITIONS * len(methods)
    if len(rows) != expected_count:
        raise ValueError(f"{study} raw rows incomplete: {len(rows)}/{expected_count}")
    grouped: dict[tuple[str, float, str], list[tuple[float, float]]] = {}
    for row in rows:
        key = row["distribution"], float(row["setting"]), row["method"]
        grouped.setdefault(key, []).append(
            (float(row["lower_bound"]), float(row["upper_bound"]))
        )
    results: list[dict[str, object]] = []
    for method in methods:
        for setting in settings:
            for distribution in DISTRIBUTIONS:
                values = np.asarray(grouped[(distribution, setting, method)], dtype=float)
                if values.shape != (REPETITIONS, 2):
                    raise ValueError((distribution, setting, method, values.shape))
                finite = np.isfinite(values).all(axis=1)
                if np.any(values[finite, 0] > values[finite, 1]):
                    raise ValueError(
                        f"Reversed interval for {(distribution, setting, method)}"
                    )
                coverage = (
                    finite
                    & (values[:, 0] <= TRUE_VALUE)
                    & (TRUE_VALUE <= values[:, 1])
                ).astype(float)
                upper = values[finite, 1]
                if upper.size < 2:
                    raise ValueError(
                        f"Fewer than two finite results for {(distribution, setting, method)}"
                    )
                half_width_denominator = 30 if study == "scarce" else None
                results.append(
                    {
                        "method": method,
                        "setting": setting,
                        "distribution": distribution,
                        "relative_ratio": float(np.mean(upper) / TRUE_VALUE),
                        "relative_ratio_half_width": _half_width(
                            upper, half_width_denominator
                        )
                        / TRUE_VALUE,
                        "upper_bound": float(np.mean(upper)),
                        "upper_bound_half_width": _half_width(
                            upper, half_width_denominator
                        ),
                        "coverage": float(np.mean(coverage)),
                        "coverage_half_width": _half_width(
                            coverage, half_width_denominator
                        ),
                        "zero_intervals": int(np.all(values == 0.0, axis=1).sum()),
                        "missing_intervals": int((~finite).sum()),
                    }
                )
    return results


def _scientific(value: float) -> str:
    if value == 0:
        return "0.00"
    exponent = math.floor(math.log10(abs(value)))
    coefficient = value / 10**exponent
    return rf"{coefficient:.2f}\times 10^{{{exponent}}}"


def render(raw_path: Path, output_dir: Path, study: str) -> Path:
    rows = aggregate(raw_path, study)
    settings = BENCHMARK_LHS if study == "benchmark" else SCARCE_THRESHOLDS
    methods = STUDY_METHODS[study]
    lookup = {
        (row["method"], row["setting"], row["distribution"]): row for row in rows
    }
    lines: list[str] = []
    for method in methods:
        for setting_index, setting in enumerate(settings):
            prefix = (
                rf"\multirow{{{len(settings)}}}{{*}}{{{METHOD_LABELS[method]}}}"
                if setting_index == 0
                else ""
            )
            cells: list[str] = []
            for distribution in DISTRIBUTIONS:
                row = lookup[(method, setting, distribution)]
                cells.extend(
                    [
                        rf"${row['relative_ratio']:.3f}(\pm {row['relative_ratio_half_width']:.3f})$",
                        rf"${_scientific(float(row['upper_bound']))}(\pm {_scientific(float(row['upper_bound_half_width']))})$",
                        rf"${row['coverage']:.3f}(\pm {row['coverage_half_width']:.3f})$",
                    ]
                )
            lines.append(
                f"{prefix} & ${setting:.3f}$ & " + " & ".join(cells) + r" \\"
            )
        lines.append(r"\hline")
    filename = "table_4_2_rows.tex" if study == "benchmark" else "table_4_3_rows.tex"
    path = output_dir / filename
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _table_block(label: str) -> str:
    text = MANUSCRIPT_PATH.read_text(encoding="utf-8")
    label_at = text.index(rf"\label{{{label}}}")
    start = text.rfind(r"\begin{table}", 0, label_at)
    if start < 0:
        raise ValueError(label)
    return text[start:label_at]


_PAIR = re.compile(
    r"([0-9.]+)"
    r"(?:\s*\\times\s*10\^\{(-?\d+)\})?"
    r"(?:\\\s*)?\s*\(\\pm\s*"
    r"([0-9.]+)"
    r"(?:\s*\\times\s*10\^\{(-?\d+)\})?"
    r"\)"
)


def _reference_rows(study: str) -> list[dict[str, object]]:
    settings = BENCHMARK_LHS if study == "benchmark" else SCARCE_THRESHOLDS
    methods = STUDY_METHODS[study]
    block = _table_block("tb5" if study == "benchmark" else "tb5_scarce")
    parsed: list[dict[str, object]] = []
    for line in block.splitlines():
        pairs = _PAIR.findall(line)
        setting_match = re.search(r"&\s*\$([0-9]+\.[0-9]+)\$", line)
        if not setting_match or len(pairs) != 9:
            continue
        values: list[tuple[float, float]] = []
        for mean, mean_exp, half_width, half_width_exp in pairs:
            values.append(
                (
                    float(mean) * (10 ** int(mean_exp) if mean_exp else 1.0),
                    float(half_width)
                    * (10 ** int(half_width_exp) if half_width_exp else 1.0),
                )
            )
        parsed.append({"setting": float(setting_match.group(1)), "values": values})
    expected_rows = len(methods) * len(settings)
    if len(parsed) != expected_rows:
        raise ValueError(
            f"Expected {expected_rows} rows from manuscript, parsed {len(parsed)}"
        )
    for index, row in enumerate(parsed):
        row["method"] = methods[index // len(settings)]
        expected_setting = settings[index % len(settings)]
        if not math.isclose(float(row["setting"]), expected_setting):
            raise ValueError((row["setting"], expected_setting))
    return parsed


def verify(raw_path: Path, output_dir: Path, study: str) -> Path:
    actual_rows = aggregate(raw_path, study)
    settings = BENCHMARK_LHS if study == "benchmark" else SCARCE_THRESHOLDS
    actual = {
        (row["method"], row["setting"], row["distribution"]): row
        for row in actual_rows
    }
    reference_rows = _reference_rows(study)
    comparisons: list[dict[str, object]] = []
    fields = (
        "relative_ratio",
        "relative_ratio_half_width",
        "upper_bound",
        "upper_bound_half_width",
        "coverage",
        "coverage_half_width",
    )
    for reference in reference_rows:
        method = str(reference["method"])
        setting = float(reference["setting"])
        values = list(reference["values"])  # type: ignore[arg-type]
        for distribution_index, distribution in enumerate(DISTRIBUTIONS):
            row = actual[(method, setting, distribution)]
            reference_values = (
                values[3 * distribution_index],
                values[3 * distribution_index + 1],
                values[3 * distribution_index + 2],
            )
            flattened_reference = (
                reference_values[0][0],
                reference_values[0][1],
                reference_values[1][0],
                reference_values[1][1],
                reference_values[2][0],
                reference_values[2][1],
            )
            for field, expected in zip(fields, flattened_reference):
                generated = float(row[field])
                comparisons.append(
                    {
                        "method": method,
                        "setting": setting,
                        "distribution": distribution,
                        "field": field,
                        "generated": generated,
                        "manuscript": expected,
                        "absolute_difference": abs(generated - expected),
                    }
                )
    tolerances = {
        "relative_ratio": 0.02,
        "relative_ratio_half_width": 0.02,
        "upper_bound": 1e-4,
        "upper_bound_half_width": 1e-4,
        "coverage": 0.01,
        "coverage_half_width": 0.01,
    }
    within = sum(
        float(item["absolute_difference"]) <= tolerances[str(item["field"])] + 1e-12
        for item in comparisons
    )
    exceptions = [
        item
        for item in comparisons
        if float(item["absolute_difference"]) > tolerances[str(item["field"])] + 1e-12
    ]
    reference_lookup = {
        (
            str(item["method"]),
            float(item["setting"]),
            str(item["distribution"]),
            str(item["field"]),
        ): float(item["manuscript"])
        for item in comparisons
    }
    coverage_comparisons = [
        item for item in comparisons if item["field"] == "coverage"
    ]
    undercoverage_agreement = sum(
        (float(item["generated"]) < 0.90)
        == (float(item["manuscript"]) < 0.90)
        for item in coverage_comparisons
    )
    generated_undercoverage = sum(
        float(item["generated"]) < 0.90 for item in coverage_comparisons
    )
    manuscript_undercoverage = sum(
        float(item["manuscript"]) < 0.90 for item in coverage_comparisons
    )
    dro_nominal_generated = sum(
        float(actual[("dro", setting, distribution)]["coverage"]) >= 0.95
        for setting in settings
        for distribution in DISTRIBUTIONS
    )
    dro_nominal_manuscript = sum(
        reference_lookup[("dro", setting, distribution, "coverage")] >= 0.95
        for setting in settings
        for distribution in DISTRIBUTIONS
    )
    dro_most_conservative_generated = sum(
        float(actual[("dro", setting, distribution)]["relative_ratio"])
        >= max(
            float(actual[(method, setting, distribution)]["relative_ratio"])
            for method in STUDY_METHODS[study][1:]
        )
        for setting in settings
        for distribution in DISTRIBUTIONS
    )
    dro_most_conservative_manuscript = sum(
        reference_lookup[("dro", setting, distribution, "relative_ratio")]
        >= max(
            reference_lookup[
                (method, setting, distribution, "relative_ratio")
            ]
            for method in STUDY_METHODS[study][1:]
        )
        for setting in settings
        for distribution in DISTRIBUTIONS
    )
    zero_summary = {
        method: sum(
            int(row["zero_intervals"])
            for row in actual_rows
            if row["method"] == method
        )
        for method in STUDY_METHODS[study]
    }
    missing_summary = {
        method: sum(
            int(row["missing_intervals"])
            for row in actual_rows
            if row["method"] == method
        )
        for method in STUDY_METHODS[study]
    }
    correlations = {}
    for field in ("relative_ratio", "upper_bound", "coverage"):
        selected = [item for item in comparisons if item["field"] == field]
        correlations[field] = float(
            np.corrcoef(
                [float(item["generated"]) for item in selected],
                [float(item["manuscript"]) for item in selected],
            )[0, 1]
        )
    worst = sorted(
        comparisons,
        key=lambda item: float(item["absolute_difference"]),
        reverse=True,
    )[:15]
    display = "Table 4.2" if study == "benchmark" else "Table 4.3"
    report = [
        f"# {display} verification report",
        "",
        f"- Repetitions: {REPETITIONS} per cell",
        f"- Complete raw method rows: {len(actual_rows) * REPETITIONS}",
        "- Existing implementations reused: D=2 chi-square DRO plus MLE-v1, MLE-v2, PL, BI, and PWM",
        "- Synthetic samples, DRO calibration, and R-based estimators use the explicit `20220222 + repetition` seed; this makes BI MCMC repeatable",
        f"- Historical DRO bootstrap stream: `{BOOTSTRAP_RNG_BY_STUDY[study]}`",
        "- Explicit `[0, 0]` fallback intervals by method: "
        + ", ".join(f"`{method}` {count}" for method, count in zero_summary.items()),
        "- Missing/non-finite intervals by method: "
        + ", ".join(f"`{method}` {count}" for method, count in missing_summary.items()),
        f"- Fields within the agreed field-specific tolerances: {within}/{len(comparisons)}",
        f"- Fields outside tolerance: {len(exceptions)}",
        "- Tolerances: upper-bound fields `1e-4`, corresponding relative-ratio fields `0.02`, coverage fields `0.01`",
        f"- Under-90% coverage classification agreement: {undercoverage_agreement}/{len(coverage_comparisons)} cells; generated count {generated_undercoverage}, manuscript count {manuscript_undercoverage}",
        f"- DRO cells at or above nominal 95% coverage: generated {dro_nominal_generated}/{len(settings) * len(DISTRIBUTIONS)}; manuscript {dro_nominal_manuscript}/{len(settings) * len(DISTRIBUTIONS)}",
        f"- Cells where DRO is at least as conservative as every conventional method: generated {dro_most_conservative_generated}/{len(settings) * len(DISTRIBUTIONS)}; manuscript {dro_most_conservative_manuscript}/{len(settings) * len(DISTRIBUTIONS)}",
        "- Generated/manuscript behavioral correlations: "
        + ", ".join(
            f"`{field}` {correlation:.6f}"
            for field, correlation in correlations.items()
        ),
        "- Scientific acceptance is based on reproducing the relative conservativeness and under-coverage pattern; tolerance exceptions remain listed",
        "",
        "| Method | Setting | Distribution | Field | Generated | Manuscript | Absolute difference |",
        "| --- | ---: | --- | --- | ---: | ---: | ---: |",
    ]
    for item in worst:
        report.append(
            f"| `{item['method']}` | {item['setting']} | `{item['distribution']}` | "
            f"`{item['field']}` | {item['generated']:.8g} | "
            f"{item['manuscript']:.8g} | {item['absolute_difference']:.3g} |"
        )
    path = output_dir / f"{study}_verification_report.md"
    path.write_text("\n".join(report) + "\n", encoding="utf-8")
    comparison_path = output_dir / f"{study}_comparisons.csv"
    with comparison_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=comparisons[0].keys())
        writer.writeheader()
        writer.writerows(comparisons)
    return path


def _parse_studies(value: str) -> tuple[str, ...]:
    if value == "all":
        return ("benchmark", "scarce")
    requested = tuple(part.strip() for part in value.split(",") if part.strip())
    invalid = set(requested) - {"benchmark", "scarce"}
    if not requested or invalid:
        raise ValueError(f"Invalid studies: {sorted(invalid)}")
    return requested


def spot_check(output_dir: Path) -> Path:
    """Run and compare the bounded manuscript-facing raw audit entries."""
    output_dir.mkdir(parents=True, exist_ok=True)
    rows: list[dict[str, object]] = []
    for study, distribution, setting, repetition in SPOT_TASKS:
        LOGGER.info(
            "Spot check: %s %s setting=%s repetition=%d",
            study,
            distribution,
            setting,
            repetition,
        )
        rows.extend(_run_task(Task(study, distribution, setting, repetition)))
    raw_path = output_dir / "spot_check_results.csv"
    with raw_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)

    comparisons: list[dict[str, object]] = []
    for row in rows:
        key = (
            str(row["study"]),
            str(row["distribution"]),
            float(row["setting"]),
            int(row["repetition"]),
            str(row["method"]),
        )
        reference_lower, reference_upper = SPOT_REFERENCES[key]
        for bound, reference in (
            ("lower_bound", reference_lower),
            ("upper_bound", reference_upper),
        ):
            if reference is None:
                continue
            generated = float(row[bound])
            comparisons.append(
                {
                    "study": key[0],
                    "distribution": key[1],
                    "setting": key[2],
                    "repetition": key[3],
                    "method": key[4],
                    "bound": bound,
                    "generated": generated,
                    "historical": reference,
                    "absolute_difference": abs(generated - reference),
                    "coverage_agrees": (
                        generated >= TRUE_VALUE
                    )
                    == (reference >= TRUE_VALUE)
                    if bound == "upper_bound"
                    else "",
                }
            )
    comparison_path = output_dir / "spot_check_comparisons.csv"
    with comparison_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=comparisons[0].keys())
        writer.writeheader()
        writer.writerows(comparisons)

    deterministic = [
        item for item in comparisons if item["method"] != "bayesian"
    ]
    bayesian = [item for item in comparisons if item["method"] == "bayesian"]
    deterministic_within = sum(
        float(item["absolute_difference"]) <= 1e-8 for item in deterministic
    )
    upper_coverage_agreement = sum(
        item["coverage_agrees"] is True
        for item in comparisons
        if item["bound"] == "upper_bound"
    )
    upper_comparisons = sum(
        item["bound"] == "upper_bound" for item in comparisons
    )
    worst_bayesian = max(
        float(item["absolute_difference"]) for item in bayesian
    )
    report = [
        "# Tables 4.2 and 4.3 raw-entry spot check",
        "",
        f"- Replicate groups: {len(SPOT_TASKS)}",
        f"- Method intervals: {len(rows)}",
        f"- Compared historical bound fields: {len(comparisons)}",
        f"- Non-Bayesian fields within `1e-8`: {deterministic_within}/{len(deterministic)}",
        f"- Largest seeded-BI versus unseeded-historical difference: `{worst_bayesian:.6g}`",
        f"- Upper-bound coverage classification agreement: {upper_coverage_agreement}/{upper_comparisons}",
        "- Standard-size DRO uses the historical Python bootstrap stream; scarce-data DRO uses its later NumPy stream",
        "- MLE-v1 uses a null PDF graphics device in headless workers; this restores the retained adaptive threshold calculation without changing it",
        "- These are raw-entry spot checks, not 200-repetition aggregate reproductions",
        "- Full generation, checkpointing, aggregation, LaTeX rendering, and manuscript comparison remain available through the `all` stage",
        "",
        "| Study | Distribution | Setting | Rep | Method | Bound | Generated | Historical | Difference |",
        "| --- | --- | ---: | ---: | --- | --- | ---: | ---: | ---: |",
    ]
    for item in sorted(
        comparisons,
        key=lambda value: float(value["absolute_difference"]),
        reverse=True,
    ):
        report.append(
            f"| `{item['study']}` | `{item['distribution']}` | "
            f"{item['setting']} | {item['repetition']} | `{item['method']}` | "
            f"`{item['bound']}` | {item['generated']:.10g} | "
            f"{item['historical']:.10g} | {item['absolute_difference']:.3g} |"
        )
    report_path = output_dir / "spot_check_report.md"
    report_path.write_text("\n".join(report) + "\n", encoding="utf-8")
    return report_path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "stage", choices=("generate", "render", "verify", "spot-check", "all")
    )
    parser.add_argument("--study", default="all")
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--workers", type=int, default=DEFAULT_WORKERS)
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    if args.stage == "spot-check":
        spot_check(args.output_dir)
        return
    studies = _parse_studies(args.study)
    raw_path = args.output_dir / "raw_results.csv"
    if args.stage in {"generate", "all"}:
        raw_path = generate(args.output_dir, studies, args.workers)
    if args.stage in {"render", "all"}:
        for study in studies:
            render(raw_path, args.output_dir, study)
    if args.stage in {"verify", "all"}:
        for study in studies:
            verify(raw_path, args.output_dir, study)


if __name__ == "__main__":
    main()
